def measure(text,scale=1):return(sum(2 if c==' 'else 4 for c in text)-1)*scale
def draw(im,text,xy,scale=1,color='#202c2d'):
 d=ImageDraw.Draw(im);x,y=xy
 for c in text:
  if c==' ':x+=2*scale;continue
  for row,line in enumerate(GLYPHS[c]):
   for col,v in enumerate(line):
    if v=='1':d.rectangle((x+col*scale,y+row*scale,x+(col+1)*scale-1,y+(row+1)*scale-1),fill=color)
  x+=4*scale
