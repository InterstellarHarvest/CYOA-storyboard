const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = process.env.QA_OUTPUT_DIR || __dirname;
const url = process.env.GALLERY_URL || 'http://127.0.0.1:8773/v05-628-regeneration/';
(async()=>{
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  fs.mkdirSync(path.join(root,'screenshots'),{recursive:true});
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[],failedRequests=[],checks=[];
  page.on('pageerror',e=>errors.push(String(e)));
  page.on('requestfailed',r=>failedRequests.push(r.url()));
  await page.goto(url,{waitUntil:'networkidle'});
  await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())));
  assert.equal(await page.locator('.candidate').count(),1);
  checks.push('Exactly one fresh A01 trial; other five candidates linked in preserved gallery');
  async function checkImage(w,h){
    await page.locator('#scene').evaluate(i=>i.decode());
    const m=await page.locator('#scene').evaluate(i=>({w:i.width,h:i.height,nw:i.naturalWidth,nh:i.naturalHeight,rendering:getComputedStyle(i).imageRendering}));
    assert.deepEqual([m.w,m.h,m.nw,m.nh],[w,h,w,h]);
    assert.ok(['pixelated','crisp-edges'].includes(m.rendering));
  }
  await checkImage(1256,824);
  await page.locator('#scene').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'screenshots/fresh-2x-desktop.png')});
  checks.push('Fresh preview displays exactly 1256x824 with integer rendering');
  await page.locator('[data-view="old4"]').click();
  await checkImage(1256,824);
  await page.screenshot({path:path.join(root,'screenshots/previous-4x-desktop.png')});
  checks.push('Previous 4x reference switches in place at the same 1256x824 display size');
  await page.locator('[data-view="new1"]').click();
  await checkImage(628,412);
  await page.screenshot({path:path.join(root,'screenshots/fresh-1x-desktop.png')});
  checks.push('Fresh 1x working export displays exactly 628x412');
  await page.setViewportSize({width:390,height:844});
  await page.goto(url,{waitUntil:'networkidle'});
  await page.locator('img').evaluateAll(imgs=>Promise.all(imgs.map(i=>i.decode())));
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await checkImage(1256,824);
  assert.ok(await page.locator('.candidate .viewport').evaluate(n=>n.scrollWidth>n.clientWidth));
  await page.screenshot({path:path.join(root,'screenshots/mobile.png')});
  checks.push('390px mobile page has bounded scrolling and no fit-to-width image scaling or document overflow');
  assert.equal(errors.length,0); assert.equal(failedRequests.length,0);
  checks.push('All visible images decode; no page exceptions or failed requests');
  const report={result:'PASS',url,browser:await browser.version(),checks,errors,failedRequests,scope:'Gallery behavior only; does not override failed exact-source dimensions or unproven native authorship.'};
  fs.writeFileSync(path.join(root,'browser-qa.json'),JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report,null,2));
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
