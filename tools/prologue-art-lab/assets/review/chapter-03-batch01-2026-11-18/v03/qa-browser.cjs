const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const root = __dirname;
const url = process.env.GALLERY_URL || 'http://127.0.0.1:8771/';

(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  const errors = [];
  const failedRequests = [];
  const checks = [];
  fs.mkdirSync(path.join(root, 'screenshots'), {recursive: true});
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, deviceScaleFactor: 1});
  page.on('pageerror', error => errors.push(String(error)));
  page.on('requestfailed', req => failedRequests.push(req.url()));
  await page.goto(url, {waitUntil: 'networkidle'});
  await page.locator('img').evaluateAll(imgs => Promise.all(imgs.map(i => i.decode())));
  assert.equal(await page.locator('.candidate').count(), 6);
  checks.push('Exactly six current candidate cards; superseded studies are links only');
  const metrics = () => page.locator('img.art').evaluateAll(imgs => imgs.map(i => ({width:i.width,height:i.height,w:Number(i.dataset.w),h:Number(i.dataset.h),naturalWidth:i.naturalWidth,naturalHeight:i.naturalHeight,rendering:getComputedStyle(i).imageRendering})));
  let images = await metrics();
  assert.ok(images.every(i => i.width === i.w && i.height === i.h && i.naturalWidth === i.w && i.naturalHeight === i.h));
  checks.push('All candidate, comparison, composite and edge-proof images load at exact 1x intrinsic dimensions');
  assert.ok(images.every(i => ['pixelated','crisp-edges'].includes(i.rendering)));
  checks.push('Browser uses pixelated/crisp-edge image rendering');
  await page.screenshot({path:path.join(root,'screenshots/gallery-desktop-1x.png')});
  await page.locator('[data-scale="4"]').click();
  images = await metrics();
  assert.ok(images.every(i => i.width === i.w * 4 && i.height === i.h * 4));
  checks.push('4x control applies exact integer dimensions to every displayed image');
  await page.locator('#CH3-A01-restroom').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'screenshots/restroom-desktop-4x.png')});
  assert.ok(await page.locator('.viewport').evaluateAll(nodes => nodes.some(n=>n.scrollWidth>n.clientWidth)));
  checks.push('4x views scroll in bounded containers without fractional fit-to-width scaling');
  await page.locator('[data-scale="1"]').click();
  await page.locator('#composites').scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(root,'screenshots/composites-desktop-1x.png')});
  await page.setViewportSize({width:390,height:844});
  await page.goto(url, {waitUntil:'networkidle'});
  await page.locator('img').evaluateAll(imgs => Promise.all(imgs.map(i => i.decode())));
  await page.screenshot({path:path.join(root,'screenshots/gallery-mobile-1x.png')});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  checks.push('390px mobile page has no horizontal document overflow; artwork scrolls within its image containers');
  assert.equal(errors.length,0);
  assert.equal(failedRequests.length,0);
  checks.push('No page exceptions or failed network requests');
  const result = {result:'PASS',url,browser:await browser.version(),checks,errors,failedRequests,
    interpretation:'Gallery behavior only. Does not approve art or override the original-native authorship failure in qa.json.'};
  fs.writeFileSync(path.join(root,'browser-qa.json'),JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result,null,2));
  await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
